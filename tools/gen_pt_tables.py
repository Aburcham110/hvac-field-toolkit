#!/usr/bin/env python3
"""Regenerate the static PT_TABLES literal in src/hvac_field_toolkit/superheat.py.

Dev-only helper: requires CoolProp (``pip install CoolProp``; generated with
CoolProp 8.0.0). The package itself has NO CoolProp dependency at runtime.

Usage:  python tools/gen_pt_tables.py > /tmp/pt.txt   (then paste into superheat.py)

Method
------
* Saturation pressure from CoolProp HEOS at quality 1 (dew / saturated vapor)
  and quality 0 (bubble / saturated liquid), every 5 °F from -40 to 130 °F.
* psig = psia - 14.696 (sea-level atmosphere). 1 psi = 6894.757 Pa.
* Predefined CoolProp fluids/blends: R410A, R22, R134a, R404A, R407C, R32.
* R-454B is not predefined in CoolProp 8.0.0, so it is built as a mixture of
  R32/R1234yf 68.9/31.1 wt % (ASHRAE 34 composition), converted to mole
  fractions. Cross-checked against the Chemours Opteon(TM) XL41 (R-454B)
  Temperature-Pressure Data (Eng), C-10270 rev 07-23:
  40 °F -> 107.0 psig sat vap / 112.0 psig sat liq;
  100 °F -> 291.0 psig sat vap / 300.7 psig sat liq.
  Agreement is within 0.5 °F at those points.
"""
import CoolProp
import CoolProp.CoolProp as CP

PA_PER_PSI = 6894.757
ATM_PSIA = 14.696
TEMPS_F = list(range(-40, 131, 5))


def _r454b() -> str:
    m32, myf = CP.PropsSI("M", "R32"), CP.PropsSI("M", "R1234yf")
    n32, nyf = 0.689 / m32, 0.311 / myf
    x = n32 / (n32 + nyf)
    return f"HEOS::R32[{x:.10f}]&R1234yf[{1 - x:.10f}]"


FLUIDS = {
    "R-410A": "HEOS::R410A",
    "R-22": "HEOS::R22",
    "R-134a": "HEOS::R134a",
    "R-404A": "HEOS::R404A",
    "R-407C": "HEOS::R407C",
    "R-32": "HEOS::R32",
    "R-454B": _r454b(),
}


def psig(fluid: str, t_f: float, q: int) -> float:
    t_k = (t_f - 32.0) / 1.8 + 273.15
    return CP.PropsSI("P", "T", t_k, "Q", q, fluid) / PA_PER_PSI - ATM_PSIA


def main() -> None:
    print(f"# Generated by tools/gen_pt_tables.py (CoolProp {CoolProp.__version__})")
    print("# (Tsat °F, dew psig, bubble psig)")
    print("PT_TABLES: Dict[str, List[Tuple[float, float, float]]] = {")
    for name, fluid in FLUIDS.items():
        print(f'    "{name}": [')
        rows = [(t, psig(fluid, t, 1), psig(fluid, t, 0)) for t in TEMPS_F]
        for i in range(0, len(rows), 3):
            chunk = ", ".join(f"({t}, {d:.1f}, {b:.1f})" for t, d, b in rows[i:i + 3])
            print(f"        {chunk},")
        print("    ],")
    print("}")


if __name__ == "__main__":
    main()
